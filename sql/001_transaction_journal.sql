CREATE TABLE IF NOT EXISTS transaction_journal (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
 event_uuid CHAR(36) NOT NULL,
 recorded_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 event_kind VARCHAR(40) NOT NULL,
 listing_key VARCHAR(100) DEFAULT NULL,
 actor_guid INT UNSIGNED NOT NULL,
 counterparty_guid INT UNSIGNED NOT NULL DEFAULT 0,
 item_id INT UNSIGNED NOT NULL,
 quantity INT UNSIGNED NOT NULL,
 auction_id INT UNSIGNED NOT NULL DEFAULT 0,
 house_id INT UNSIGNED NOT NULL DEFAULT 0,
 start_bid BIGINT UNSIGNED NOT NULL DEFAULT 0,
 buyout BIGINT UNSIGNED NOT NULL DEFAULT 0,
 gross BIGINT UNSIGNED NOT NULL DEFAULT 0,
 deposit BIGINT UNSIGNED NOT NULL DEFAULT 0,
 fee BIGINT UNSIGNED NOT NULL DEFAULT 0,
 proceeds BIGINT UNSIGNED NOT NULL DEFAULT 0,
 actor_ahbot TINYINT UNSIGNED NOT NULL DEFAULT 0,
 counterparty_ahbot TINYINT UNSIGNED NOT NULL DEFAULT 0,
 PRIMARY KEY(id),
 UNIQUE KEY event_identity(event_uuid),
 UNIQUE KEY listing_event(listing_key,event_kind),
 KEY actor_time(actor_guid,recorded_at),
 KEY counterparty_time(counterparty_guid,recorded_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
